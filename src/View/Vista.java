    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        try {
            String seleccion = (String) jComboBoxTipos.getSelectedItem();
            double costoActual = 0;

            if (seleccion.equals("Envío en Bicicleta")) {

                String trackingId = txtTrackingId.getText();
                int distance = Integer.parseInt(txtDistanciaKm.getText());
                controlador.registrarBikeDelivery(trackingId, distance);
                costoActual = controlador.getLista().get(controlador.getLista().size() - 1).calculateCharge();

            } else if (seleccion.equals("Envío en Furgoneta")) {

                String trackingId = txtTrackingId.getText();
                int distance = Integer.parseInt(txtDistanciaKm.getText());
                controlador.registrarVanDelivery(trackingId, distance);
                costoActual = controlador.getLista().get(controlador.getLista().size() - 1).calculateCharge();

            } else if (seleccion.equals("Empaque")) {

                int items = Integer.parseInt(txtItems.getText());
                int chargePerItem = Integer.parseInt(txtChargePerItem.getText());
                controlador.registrarPackaging(items, chargePerItem);
                costoActual = controlador.getLista().get(controlador.getLista().size() - 1).calculateCharge();

            }

            actualizarResultados();

            double totalGeneral = controlador.calcularTotalGeneral();
            JOptionPane.showMessageDialog(this,
                    "¡Registrado con éxito!\n"
                    + "Costo de este elemento: ₡" +  costoActual + "\n"
                    + "Total Acumulado: ₡" +  totalGeneral);

            limpiarCampos();
            generarTrackingIdAutomatico();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese valores válidos.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

