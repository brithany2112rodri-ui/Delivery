    private void generarTrackingIdAutomatico() {
        String trackingId = "TRK-" + UUID.randomUUID().toString().substring(0, 5).toUpperCase();//El UUID,randomUUID().toString() es una clase de java para generar valores unicos
        txtTrackingId.setText(trackingId);
    }

    private void actualizarEstadoCampos() {
        String seleccion = (String) jComboBoxTipos.getSelectedItem();

        if (seleccion != null) {
            if (seleccion.equals("Envío en Bicicleta") || seleccion.equals("Envío en Furgoneta")) {
                txtTrackingId.setEnabled(true);
                txtDistanciaKm.setEnabled(true);
                txtItems.setEnabled(false);
                txtChargePerItem.setEnabled(false);
                txtItems.setText("");
                txtChargePerItem.setText("");
            } else if (seleccion.equals("Empaque")) {
                txtTrackingId.setEnabled(false);
                txtDistanciaKm.setEnabled(false);
                txtTrackingId.setText("");
                txtDistanciaKm.setText("");
                txtItems.setEnabled(true);
                txtChargePerItem.setEnabled(true);
            }
        }
    }

    private void actualizarResultados() {// StringBuilder sirve para hacer cadenas de texto grandes, se uso para juntar todos los elementos  y el total
        StringBuilder sb = new StringBuilder();
        sb.append("Cobros:\n");

        int index = 1;
        for (Chargeable item : controlador.getLista()) {
            sb.append(index).append(" Tipo: ").append(item.getClass().getSimpleName())
                    .append(" Costo: ₡").append(item.calculateCharge())
                    .append("\n");
            index++;
        }

        sb.append("Total: ₡").append (controlador.calcularTotalGeneral());

        txtAreaResultados.setText(sb.toString());
    }

    private void limpiarCampos() {
        txtDistanciaKm.setText("");
        txtItems.setText("");
        txtTrackingId.setText("");
    }

